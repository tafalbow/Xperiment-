export class BpsDataProvider {
  /**
   * Retrieves metadata for categories and indicators
   */
  static getMetadata() {
    return {
      status: "SUCCESS",
      total_categories: BPS_CATEGORIES.length,
      categories: BPS_CATEGORIES,
      total_indicators: BPS_CANONICAL_INDICATORS.length,
      indicators: BPS_CANONICAL_INDICATORS
    };
  }

  /**
   * Returns filtered matrix with recalculated descriptive metrics (L3Y, min, max, latest, yoy)
   */
  static getMatrix({ category = 'ALL', startYear = 1990, endYear = 2026, q = '' } = {}) {
    const sYear = Math.max(1990, Math.min(parseInt(startYear) || 1990, 2026));
    const eYear = Math.max(sYear, Math.min(parseInt(endYear) || 2026, 2026));
    const queryClean = (q || '').trim().toLowerCase();

    const filtered = BPS_CANONICAL_INDICATORS.filter(ind => {
      if (category && category !== 'ALL' && ind.category !== category) {
        return false;
      }
      if (queryClean) {
        const match = (
          ind.name.toLowerCase().includes(queryClean) ||
          ind.id.toLowerCase().includes(queryClean) ||
          ind.source.toLowerCase().includes(queryClean) ||
          ind.category_label.toLowerCase().includes(queryClean) ||
          (ind.description && ind.description.toLowerCase().includes(queryClean))
        );
        if (!match) return false;
      }
      return true;
    });

    const yearsRange = [];
    for (let y = sYear; y <= eYear; y++) {
      yearsRange.push(String(y));
    }

    const processedIndicators = filtered.map(ind => {
      const slicedValues = {};
      const valsList = [];

      for (let y = sYear; y <= eYear; y++) {
        const yStr = String(y);
        const val = ind.values[yStr] !== undefined ? ind.values[yStr] : 0.0;
        slicedValues[yStr] = val;
        valsList.push(val);
      }

      const latestVal = slicedValues[String(eYear)] || 0.0;
      const prevVal = slicedValues[String(eYear - 1)] || 0.0;
      const yoyGrowth = prevVal !== 0.0
        ? parseFloat((((latestVal - prevVal) / prevVal) * 100.0).toFixed(2))
        : 0.0;

      const l3ySlice = [];
      const l3yStart = Math.max(sYear, eYear - 2);
      for (let y = l3yStart; y <= eYear; y++) {
        l3ySlice.push(slicedValues[String(y)] || 0.0);
      }
      const l3yAvg = l3ySlice.length > 0
        ? parseFloat((l3ySlice.reduce((a, b) => a + b, 0) / l3ySlice.length).toFixed(2))
        : 0.0;

      const minVal = valsList.length > 0 ? Math.min(...valsList) : 0.0;
      const maxVal = valsList.length > 0 ? Math.max(...valsList) : 0.0;

      return {
        ...ind,
        values: slicedValues,
        min_val: minVal,
        max_val: maxVal,
        latest_val: latestVal,
        l3y_avg: l3yAvg,
        yoy_growth: yoyGrowth
      };
    });

    return {
      status: "SUCCESS",
      total_indicators: processedIndicators.length,
      category: category,
      start_year: sYear,
      end_year: eYear,
      years: yearsRange,
      categories: BPS_CATEGORIES,
      indicators: processedIndicators
    };
  }

  /**
   * Generates and triggers Excel download using client-side SheetJS XLSX
   */
  static downloadExcel({ category = 'ALL', startYear = 1990, endYear = 2026 } = {}) {
    if (typeof XLSX === 'undefined') {
      console.error('SheetJS (XLSX) tidak tersedia di window.');
      return;
    }

    const matrix = this.getMatrix({ category, startYear, endYear });
    const years = matrix.years;
    const indicators = matrix.indicators;

    const wb = XLSX.utils.book_new();

    // Sheet 1: Kompilasi Data
    const sheet1Data = [
      ["INDOEKONOMI data — Kompilasi Indikator Statutori BPS (" + startYear + " - " + endYear + ")"],
      [],
      ["No", "Nama Indikator Resmi BPS", "Kategori", "Satuan", "Sumber Resmi", "Min", "Max", "Terkini (" + endYear + ")", ...years]
    ];

    indicators.forEach((ind, idx) => {
      const row = [
        idx + 1,
        ind.name,
        ind.category_label,
        ind.unit,
        ind.source,
        ind.min_val,
        ind.max_val,
        ind.latest_val,
        ...years.map(y => ind.values[y] !== undefined ? ind.values[y] : 0.0)
      ];
      sheet1Data.push(row);
    });

    const ws1 = XLSX.utils.aoa_to_sheet(sheet1Data);
    XLSX.utils.book_append_sheet(wb, ws1, "Kompilasi Data BPS");

    // Sheet 2: Statistik Deskriptif
    const sheet2Data = [
      ["Statistik Deskriptif & Metrik Ringkasan Indikator BPS"],
      [],
      ["No", "Nama Indikator", "Kategori", "Satuan", "Nilai Terkini", "Rata-rata L3Y", "Min", "Max", "Pertumbuhan YoY (%)"]
    ];

    indicators.forEach((ind, idx) => {
      sheet2Data.push([
        idx + 1,
        ind.name,
        ind.category_label,
        ind.unit,
        ind.latest_val,
        ind.l3y_avg,
        ind.min_val,
        ind.max_val,
        ind.yoy_growth
      ]);
    });

    const ws2 = XLSX.utils.aoa_to_sheet(sheet2Data);
    XLSX.utils.book_append_sheet(wb, ws2, "Statistik Deskriptif");

    const filename = `Kompilasi_Data_BPS_${category}_${startYear}_${endYear}.xlsx`;
    XLSX.writeFile(wb, filename);
  }

  /**
   * Generates and triggers CSV download directly in browser
   */
  static downloadCsv({ category = 'ALL', startYear = 1990, endYear = 2026 } = {}) {
    const matrix = this.getMatrix({ category, startYear, endYear });
    const years = matrix.years;
    const indicators = matrix.indicators;

    const headers = ["ID", "Nama Indikator", "Kategori BPS", "Satuan", "Sumber Resmi BPS", "Min", "Max", "Terkini", ...years];
    const rows = [headers.map(h => `"${h}"`).join(",")];

    indicators.forEach(ind => {
      const row = [
        `"${ind.id}"`,
        `"${ind.name}"`,
        `"${ind.category_label}"`,
        `"${ind.unit}"`,
        `"${ind.source}"`,
        ind.min_val,
        ind.max_val,
        ind.latest_val,
        ...years.map(y => ind.values[y] !== undefined ? ind.values[y] : 0.0)
      ];
      rows.push(row.join(","));
    });

    const csvContent = "\uFEFF" + rows.join("\r\n");
    const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
    const link = document.createElement("a");
    const url = URL.createObjectURL(blob);
    link.setAttribute("href", url);
    link.setAttribute("download", `Kompilasi_Data_BPS_${category}_${startYear}_${endYear}.csv`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  }
}
